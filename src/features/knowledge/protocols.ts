/** Where in the day a protocol wants to live. */
interface Anchor {
  /** 'wake'/'sleep' offset in minutes, or a fixed start. */
  kind: 'wake' | 'sleep' | 'fixed';
  offsetMin?: number;
  start?: string;
  /** Latest acceptable start, minutes after preferred. */
  windowMin: number;
  /**
   * The hour is part of what this IS, not merely when it suits.
   *
   * Dinner moved to 09:40 has not been rescheduled, it has been turned
   * into something else — where a message to a friend at 20:00 instead of
   * 12:45 is simply a message to a friend. Wake- and sleep-anchored
   * protocols get this automatically; a fixed-anchor one has to say so,
   * because the anchor alone cannot tell a meal from an errand.
   */
  timeAnchored?: boolean;
  /**
   * A deadline, not an activity — "last coffee by", "kitchen closed".
   * The scheduler may bring these earlier but must never push them later:
   * a cutoff moved to make room has become false, not merely inconvenient.
   * Deadlines are placed rigidly and surface as unplaced rather than drift.
   */
  deadline?: boolean;
}

/**
 * Evidence quality — not all protocols are equally certain, and IntentNorth
 * says so. Expert communicators are discovery sources; the level grades
 * the underlying research, not the fame of the messenger.
 */
export type EvidenceLevel = 'A' | 'B' | 'C' | 'D' | 'E';

export const EVIDENCE_LABELS: Record<EvidenceLevel, string> = {
  A: 'Strong — meta-analyses / broad consensus',
  B: 'Good — controlled trials, or large and consistent cohorts',
  C: 'Moderate — smaller, narrower or mixed observational evidence',
  D: 'Emerging — expert practice',
  E: 'Experimental — a heuristic worth testing on yourself',
};

export interface Protocol {
  id: string;
  evidenceLevel: EvidenceLevel;
  title: string;
  pillar: Pillar;
  area: LifeArea;
  /** Goal domains this practice serves — the goal wizard reads this. */
  goalDomains: GoalDomain[];
  /** What to do, one plain sentence. */
  summary: string;
  /** Why it works — the evidence story, in plain words, no overclaiming. */
  why: string;
  /** Whose public teaching popularised it. Credit, not endorsement. */
  attribution: string[];
  days: Weekday[];
  durationMin: number;
  anchor: Anchor;
  energy: Routine['energy'];
  tier: PlanTier;
  sessionType?: SessionType;
  duringWork?: boolean;
  /** Plain-words caution. Health protocols must have one. */
  safety?: string;
  /**
   * Never chase this one. No streak, no adherence score, no missed-it
   * suggestion, no nudge — a skipped day carries no meaning.
   *
   * Life-transition protocols are the reason this exists. Someone three
   * weeks after a bereavement or a redundancy does not need the adaptation
   * engine reporting that they are 40% adherent, and the engine cannot know
   * not to: it learns the same way on everything. This is the protocol
   * saying, in data, that it is not that kind of practice.
   */
  neverNag?: boolean;
  /**
   * Who this practice is for, when it is not everybody.
   *
   * The library holds practices that only apply to some bodies — pelvic
   * floor training, pregnancy, the menopause transition, cycle tracking.
   * They were sitting in a flat list beside general training practices with
   * nothing to distinguish them, so one tap of "Add to my plan" put pelvic
   * floor training into a man's week and, a day later, the coach note gave
   * it the most prominent editorial slot on the Today screen.
   *
   * The app deliberately does not ask anybody's sex, and this does not
   * start: it is a LABEL, not a filter on the person. These practices are
   * named for who they are for, kept out of the default browse, and reached
   * on purpose rather than stumbled into. Someone who wants one still gets
   * it in two taps; nobody gets one by accident.
   */
  appliesTo?: 'femaleAnatomy' | 'pregnancy' | 'menopause';
}

