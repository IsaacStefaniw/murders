export const protocolById = (id: string): Protocol | undefined =>
  PROTOCOLS.find((p) => p.id === id);

/** Protocols that serve a goal domain, most relevant first. */
export function protocolsForDomain(domain: GoalDomain): Protocol[] {
  return PROTOCOLS.filter((p) => p.goalDomains.includes(domain));
}

function startFor(p: Protocol, profile: LifeProfile | null): string {
  const a = p.anchor;
  if (a.kind === 'wake' && profile) {
    return toHHMM(toMinutes(profile.wakeTime) + (a.offsetMin ?? 0));
  }
  if (a.kind === 'sleep' && profile) {
    return toHHMM((toMinutes(profile.sleepTime) - (a.offsetMin ?? 0) + 1440) % 1440);
  }
  return a.start ?? '12:05';
}

/**
 * Keep `count` days spread across the week rather than taking the first
 * few. Trimming [0,1,2,3,4,5,6] to [0,1] collapses a spaced practice into
 * two adjacent days, which destroys the very mechanism a spacing protocol
 * exists for — a trim that makes a protocol false rather than smaller.
 */
export function spreadDays(days: Weekday[], count: number): Weekday[] {
  if (days.length <= count) return [...days];
  const step = (days.length - 1) / (count - 1);
  const picked = new Set<Weekday>();
  for (let i = 0; i < count; i++) picked.add(days[Math.round(i * step)]);
  return [...picked].sort((a, b) => a - b);
}

/** A protocol as a schedulable routine, anchored to the user's real day. */
export function toRoutine(p: Protocol, profile: LifeProfile | null, goalId?: string): Routine {
  const start = startFor(p, profile);
  const days =
    profile?.capacity === 'minimal' && p.tier === 'could' && p.days.length > 2
      ? spreadDays(p.days, 2)
      : [...p.days];
  return {
    id: newId('r'),
    title: p.title,
    area: p.area,
    goalId,
    protocolId: p.id,
    days,
    durationMin: p.durationMin,
    preferredStart: start,
    preferredEnd: toHHMM((toMinutes(start) + p.anchor.windowMin) % 1440),
    energy: p.energy,
    // A deadline is never flexible: the placement pass may not move it later.
    flexible: !p.duringWork && !p.anchor.deadline,
    protected: false,
    duringWork: p.duringWork,
    sessionType: p.sessionType,
    tier: p.tier,
    active: true,
  };
}

/**
 * Compact grounding for the AI agents: the whole base in a few hundred
 * tokens, so suggestions the model writes stay anchored to the same
 * evidence-based library the deterministic engine plans from.
 */
/**
 * The library as grounding for a model prompt.
 *
 * Summary + evidence grade only. `why` is the evidence story we show the
 * USER; the planner needs to know what a protocol does and how well
 * supported it is, not to carry our copy in every prompt.
 *
 * Pass the pillars a prompt actually concerns. As the library grows past a
 * hundred entries, sending all of it in every call is waste — a weekly
 * training review has no use for the money protocols. Unfiltered stays
 * available and remains small enough to send, but callers should narrow.
 */
export function knowledgeContext(pillars?: Pillar[]): string {
  const scope = pillars?.length
    ? PROTOCOLS.filter((p) => pillars.includes(p.pillar))
    : PROTOCOLS;
  return scope
    .map((p) => `- ${p.title} (${PILLAR_LABELS[p.pillar]}, evidence ${p.evidenceLevel}): ${p.summary}`)
    .join('\n');
}

